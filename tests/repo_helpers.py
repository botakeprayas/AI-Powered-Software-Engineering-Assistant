def _write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def build_hazard_repo(destination: Path) -> Path:
    """Copy the sample repo, then add files the scanner and extractor must handle safely."""
    shutil.copytree(SAMPLE_REPO, destination)
    for rel, text in HAZARD_TEXT_FILES.items():
        _write(destination / rel, text.encode("utf-8"))
    for rel, data in HAZARD_BINARY_FILES.items():
        _write(destination / rel, data)
    return destination