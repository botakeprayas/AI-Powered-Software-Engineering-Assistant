"""Repository scanner: decides which files are analyzed and records why others are skipped.

Sensitive files are filtered by NAME only. They are never opened, read or logged.
"""

from __future__ import annotations

import logging
import os
from pathlib import Path

from core.repo.models import RepoFile, ScanResult, SkippedItem

logger = logging.getLogger(__name__)

MAX_FILES = 5000
MAX_FILE_BYTES = 1_000_000

SKIP_DIR_REASONS = {
    ".git": "Git internals",
    ".hg": "Mercurial internals",
    ".svn": "Subversion internals",
    ".venv": "virtual environment",
    "venv": "virtual environment",
    "env": "virtual environment",
    ".env": "virtual environment",
    "__pycache__": "Python bytecode cache",
    "site-packages": "installed packages",
    "node_modules": "JavaScript dependencies",
    "build": "build output",
    "dist": "build output",
    ".tox": "tool cache",
    ".nox": "tool cache",
    ".mypy_cache": "tool cache",
    ".pytest_cache": "tool cache",
    ".ruff_cache": "tool cache",
    ".hypothesis": "tool cache",
    ".idea": "editor settings",
    ".vscode": "editor settings",
    "__macosx": "macOS zip metadata",
}

SAFE_ENV_TEMPLATES = frozenset({".env.example", ".env.sample", ".env.template", ".env.dist"})
PRIVATE_KEY_SUFFIXES = frozenset({".pem", ".key", ".p12", ".pfx", ".jks", ".keystore", ".ppk"})
PRIVATE_KEY_NAMES = frozenset({"id_rsa", "id_dsa", "id_ecdsa", "id_ed25519"})
CREDENTIAL_FILE_NAMES = frozenset(
    {".netrc", ".pgpass", ".npmrc", ".pypirc", ".htpasswd", ".git-credentials"}
)
CREDENTIAL_PREFIXES = (
    "credential", "secret", "client_secret", "service-account", "service_account",
)
BINARY_SUFFIXES = frozenset(
    {".pyc", ".pyo", ".pyd", ".so", ".dll", ".exe", ".db", ".sqlite", ".sqlite3", ".faiss",
     ".index", ".png", ".jpg", ".jpeg", ".gif", ".ico", ".pdf", ".zip", ".tar", ".gz", ".whl"}
)
GENERATED_NAME_ENDINGS = ("_pb2.py", "_pb2_grpc.py", ".min.js", ".min.css")
GENERATED_MARKERS = (
    "@generated", "do not edit", "auto-generated", "autogenerated", "code generated",
    "generated by",
)


def dir_skip_reason(name: str) -> str | None:
    """Reason a folder with this NAME is skipped, or None."""
    lowered = name.lower()
    if lowered in SKIP_DIR_REASONS:
        return SKIP_DIR_REASONS[lowered]
    if lowered.endswith(".egg-info"):
        return "packaging metadata"
    return None


def sensitive_reason(name: str) -> str | None:
    """Reason a file with this NAME looks like it holds secrets, or None."""
    lowered = name.lower()
    if lowered == ".env" or (lowered.startswith(".env.") and lowered not in SAFE_ENV_TEMPLATES):
        return "sensitive: environment file (may hold secrets)"
    if lowered in PRIVATE_KEY_NAMES or Path(lowered).suffix in PRIVATE_KEY_SUFFIXES:
        return "sensitive: private key or certificate store"
    if lowered in CREDENTIAL_FILE_NAMES or lowered.startswith(CREDENTIAL_PREFIXES):
        return "sensitive: credentials file"
    return None


def name_skip_reason(name: str) -> str | None:
    """Skip decision that needs only the file NAME (used by the scanner and the zip loader)."""
    reason = sensitive_reason(name)
    if reason:
        return reason
    lowered = name.lower()
    if Path(lowered).suffix in BINARY_SUFFIXES:
        return "binary or compiled file"
    if lowered.endswith(GENERATED_NAME_ENDINGS):
        return "generated or minified file (by name)"
    return None


def _has_generated_header(path: Path) -> bool:
    try:
        with path.open("rb") as handle:
            head = handle.read(1024)
    except OSError:
        return False
    first_lines = head.decode("utf-8", errors="ignore").lower().splitlines()[:5]
    return any(marker in line for line in first_lines for marker in GENERATED_MARKERS)


def _join(base: str, name: str) -> str:
    return f"{base}/{name}" if base else name


def _record(result: ScanResult, path: str, kind: str, reason: str) -> None:
    result.skipped.append(SkippedItem(path, kind, reason))
    logger.debug("Skipped %s %s: %s", kind, path, reason)


def _dir_skip(path: Path, name: str) -> str | None:
    if path.is_symlink():
        return "symbolic link (not followed)"
    reason = dir_skip_reason(name)
    if reason:
        return reason
    if (path / "pyvenv.cfg").is_file():
        return "virtual environment (pyvenv.cfg found)"
    return None


def _scan_file(result: ScanResult, base: Path, rel_base: str, name: str, max_bytes: int) -> None:
    path = base / name
    rel = _join(rel_base, name)
    reason = "symbolic link (not followed)" if path.is_symlink() else name_skip_reason(name)
    size = 0
    if reason is None:
        try:
            size = path.stat().st_size
        except OSError as exc:
            reason = f"unreadable: {exc.strerror or exc}"
    if reason is None and size > max_bytes:
        reason = f"too large ({size:,} bytes; limit {max_bytes:,})"
    is_python = name.lower().endswith(".py")
    if reason is None and is_python and _has_generated_header(path):
        reason = "generated file (marker in header)"
    if reason:
        _record(result, rel, "file", reason)
    else:
        result.files.append(RepoFile(rel, size, is_python))


def scan_repository(
    root: Path, max_files: int = MAX_FILES, max_file_bytes: int = MAX_FILE_BYTES
) -> ScanResult:
    """Walk `root` and split everything into kept files and skipped items (with reasons)."""
    root_path = Path(root).resolve()
    if not root_path.is_dir():
        raise NotADirectoryError(f"Not a folder: {root_path}")
    result = ScanResult(root=root_path)

    def on_error(exc: OSError) -> None:
        _record(result, str(exc.filename), "dir", f"unreadable: {exc.strerror or exc}")

    for dirpath, dirnames, filenames in os.walk(root_path, onerror=on_error):
        base = Path(dirpath)
        rel_base = base.relative_to(root_path).as_posix()
        if rel_base == ".":
            rel_base = ""
        kept_dirs = []
        for name in sorted(dirnames):
            reason = _dir_skip(base / name, name)
            if reason:
                _record(result, _join(rel_base, name), "dir", reason)
            else:
                kept_dirs.append(name)
        dirnames[:] = kept_dirs  # os.walk only descends into the folders left in this list
        for name in sorted(filenames):
            if len(result.files) >= max_files:
                result.limit_reached = True
                message = f"file limit reached ({max_files}); remaining files not scanned"
                _record(result, _join(rel_base, name), "file", message)
                break
            _scan_file(result, base, rel_base, name, max_file_bytes)
        if result.limit_reached:
            break
    logger.info(
        "Scan of %s: %d files kept, %d skipped", root_path, len(result.files), len(result.skipped)
    )
    return result